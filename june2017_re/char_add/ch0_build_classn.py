def sub_text(sid):
    b = subq.get(int(sid))
    if b is None:
        return '%s: not in FieldSubQuest.src.lua' % sid
    desc = (re.search(r'm_wstrDescription = "([^"]*)"', b) or [0, ''])[1]
    typ = (re.search(r'SUB_QUEST_TYPE\.(\w+)', b) or [0, '?'])[1]
    dun = re.search(r'm_eDungeonID = \{(.*?)\}', b, re.S)
    npc = re.search(r'm_eKillNPCID = \{(.*?)\}', b, re.S)
    dif = re.search(r'DIFFICULTY_LEVEL\.(\w+)', b)
    bits = [sid, typ]
    if dun:
        bits.append('dungeon ' + ','.join(x for x in dun.group(1).replace(',', ' ').split()))
    if npc:
        bits.append('npc ' + ','.join(x for x in npc.group(1).replace(',', ' ').split()))
    if dif:
        bits.append(dif.group(1))
    return ' '.join(bits) + ' ("%s")' % desc


def kim(ids):
    out = subprocess.run([sys.executable, T + 'tools/kim.py', 'find', 'staged', '--ids', ','.join(str(i) for i in ids), '--cols', 'id,name,item_type,unit_class,use_level', '--limit', '0', '--tsv'],
                         capture_output=True, text=True, encoding='utf-8', errors='replace', cwd=T).stdout
    rows = {}
    for l in out.split('\n'):
        p = l.split('\t')
        if len(p) >= 5 and p[0].isdigit():
            rows[int(p[0])] = p
    return rows


